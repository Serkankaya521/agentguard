const DICTS: Record<Lang, Record<string, string>> = {tr: TR, en: EN};

type I18n = {lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Record<string, string | number>) => string};
const Context = createContext<I18n | null>(null);

function interpolate(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function I18nProvider({children}: {children: ReactNode}) {
  const [lang, setLangState] = useState<Lang>('tr');
  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'tr' || stored === 'en') setLangState(stored);
    } catch { /* storage may be blocked */ }
  }, []);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
    try { document.documentElement.lang = next; } catch { /* ignore */ }
  }, []);
  const t = useCallback((key: string, vars?: Record<string, string | number>) =>
    interpolate(DICTS[lang][key] ?? EN[key] ?? key, vars), [lang]);
  const value = useMemo(() => ({lang, setLang, t}), [lang, setLang, t]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useT(): I18n {
  const value = useContext(Context);
  if (!value) return {lang: 'en', setLang: () => undefined, t: (k, v) => interpolate(EN[k] ?? k, v)};
  return value;
}
